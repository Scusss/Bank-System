-- JAB Bank: separate USER accounts from BANK accounts.
-- Review before running; take a backup first. Written against the models in
-- app/models.py and NOT tested against your database. Adjust names if your
-- live schema differs (e.g. constraint names).
BEGIN;

-- 1. User account table: customer -> app_users (PK customer_id -> user_id)
DO $$
BEGIN
  IF to_regclass('public.customer') IS NOT NULL
     AND to_regclass('public.app_users') IS NULL THEN
    ALTER TABLE customer RENAME TO app_users;
    ALTER TABLE app_users RENAME COLUMN customer_id TO user_id;
  END IF;
END $$;

ALTER TABLE app_users ALTER COLUMN account_status TYPE VARCHAR(30);

-- 2. Roles: add the verification officer role
INSERT INTO roles (role_id, role_name, description)
SELECT (SELECT COALESCE(MAX(role_id), 0) + 1 FROM roles),
       'verification_officer',
       'Reviews identity verification requests'
WHERE NOT EXISTS (
  SELECT 1 FROM roles WHERE role_name = 'verification_officer'
);

-- 3. Account information lives on the user account
ALTER TABLE customer_details ADD COLUMN IF NOT EXISTS suffix VARCHAR(20);

-- 4. Bank accounts: new columns used by the new Account model
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS frozen_at TIMESTAMPTZ;
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS closed_at TIMESTAMPTZ;
ALTER TABLE accounts ADD COLUMN IF NOT EXISTS status_reason TEXT;
ALTER TABLE accounts ALTER COLUMN account_number TYPE VARCHAR(50);
ALTER TABLE accounts ALTER COLUMN account_type TYPE VARCHAR(50);
ALTER TABLE accounts ALTER COLUMN status TYPE VARCHAR(30);

-- 5. Identity verification requests (user -> verification officer)
CREATE TABLE IF NOT EXISTS identity_verifications (
  verification_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id         UUID NOT NULL REFERENCES app_users(user_id),
  document_type       VARCHAR(50),
  document_reference  TEXT,
  verification_status VARCHAR(30) NOT NULL,
  review_remarks      TEXT,
  reviewed_by         UUID REFERENCES app_users(user_id),
  submitted_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at         TIMESTAMPTZ
);
-- Button-only verification: ID details are optional (if the table already existed)
ALTER TABLE identity_verifications ALTER COLUMN document_type DROP NOT NULL;
ALTER TABLE identity_verifications ALTER COLUMN document_reference DROP NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_identity_verifications_one_pending
  ON identity_verifications (customer_id)
  WHERE verification_status = 'pending';

-- 6. Bank account requests (once per bank type while pending/approved)
CREATE TABLE IF NOT EXISTS account_applications (
  application_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id          UUID NOT NULL REFERENCES app_users(user_id),
  account_type         VARCHAR(50) NOT NULL,
  application_status   VARCHAR(30) NOT NULL,
  reviewed_by          UUID REFERENCES app_users(user_id),
  review_remarks       TEXT,
  submitted_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  reviewed_at          TIMESTAMPTZ,
  resulting_account_id BIGINT REFERENCES accounts(account_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_account_applications_active_type
  ON account_applications (customer_id, account_type)
  WHERE application_status IN ('pending', 'approved');

-- 7. Bank types a user may request (model: AccountTypeLimit).
--    If this table stays empty the app offers savings/checking/business.
CREATE TABLE IF NOT EXISTS account_type_limits (
  limit_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_type           VARCHAR(50) NOT NULL,
  minimum_balance        NUMERIC(19,2) NOT NULL,
  maximum_balance        NUMERIC(19,2),
  minimum_deposit        NUMERIC(19,2) NOT NULL,
  maximum_deposit        NUMERIC(19,2),
  minimum_withdrawal     NUMERIC(19,2) NOT NULL,
  maximum_withdrawal     NUMERIC(19,2),
  daily_withdrawal_limit NUMERIC(19,2),
  daily_transfer_limit   NUMERIC(19,2),
  transfer_fee           NUMERIC(19,2) NOT NULL,
  is_active              BOOLEAN NOT NULL DEFAULT TRUE,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at             TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS account_limit_overrides (
  override_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id             BIGINT NOT NULL REFERENCES accounts(account_id),
  daily_transfer_limit   NUMERIC(19,2),
  daily_withdrawal_limit NUMERIC(19,2),
  reason                 TEXT NOT NULL,
  approved_by            UUID NOT NULL REFERENCES app_users(user_id),
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at             TIMESTAMPTZ
);

-- 8. Audit log columns used by the new AuditLog model
ALTER TABLE audit_logs ADD COLUMN IF NOT EXISTS performed_by UUID REFERENCES app_users(user_id);
ALTER TABLE audit_logs ADD COLUMN IF NOT EXISTS performed_by_role VARCHAR(50);
ALTER TABLE audit_logs ADD COLUMN IF NOT EXISTS old_values JSONB;
ALTER TABLE audit_logs ADD COLUMN IF NOT EXISTS new_values JSONB;
ALTER TABLE audit_logs ALTER COLUMN entity_type TYPE VARCHAR(50);
ALTER TABLE audit_logs ALTER COLUMN entity_id TYPE TEXT USING entity_id::text;

